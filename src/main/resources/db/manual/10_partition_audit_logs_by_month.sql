-- Optional PostgreSQL migration: partition the append-only audit_logs table by month.
-- Run only after taking a Neon snapshot/backup and when audit_logs has grown large.
-- Partition pruning helps queries that constrain created_at (for example, a date range).
-- The current /admin/audit-logs page loads all rows, so this migration alone will not
-- make that page faster; add a created_at range filter/pagination in the app first.
--
-- The original table is retained as audit_logs_pre_partition for rollback/verification.
-- This is a one-time migration and intentionally aborts if that backup name already exists.

BEGIN;

DO $$
BEGIN
    IF to_regclass('public.audit_logs') IS NULL THEN
        RAISE EXCEPTION 'public.audit_logs does not exist; run the current schema first';
    END IF;
    IF to_regclass('public.audit_logs_pre_partition') IS NOT NULL THEN
        RAISE EXCEPTION 'public.audit_logs_pre_partition already exists; migration appears to have run';
    END IF;
    IF EXISTS (
        SELECT 1 FROM pg_partitioned_table p
        JOIN pg_class c ON c.oid = p.partrelid
        JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = 'public' AND c.relname = 'audit_logs'
    ) THEN
        RAISE EXCEPTION 'public.audit_logs is already partitioned';
    END IF;
END $$;

LOCK TABLE public.audit_logs IN ACCESS EXCLUSIVE MODE;
ALTER TABLE public.audit_logs RENAME TO audit_logs_pre_partition;

CREATE TABLE public.audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    action VARCHAR(255) NOT NULL,
    entity_type VARCHAR(255) NOT NULL,
    entity_id BIGINT,
    actor VARCHAR(255),
    details TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- PostgreSQL requires every unique/primary key on a partitioned table to include
    -- its partition key. id is still generated from one global identity sequence.
    CONSTRAINT pk_audit_logs_monthly PRIMARY KEY (id, created_at)
) PARTITION BY RANGE (created_at);

-- Create monthly partitions covering all existing rows and the next 12 months.
-- A DEFAULT partition catches dates outside that initial range.
DO $$
DECLARE
    month_start TIMESTAMP;
    month_end TIMESTAMP;
    final_month TIMESTAMP;
    partition_name TEXT;
BEGIN
    SELECT date_trunc('month', min(created_at)), date_trunc('month', max(created_at))
      INTO month_start, month_end
      FROM public.audit_logs_pre_partition;

    IF month_start IS NULL THEN
        month_start := date_trunc('month', CURRENT_TIMESTAMP)::timestamp;
    END IF;
    IF month_end IS NULL THEN
        month_end := month_start;
    END IF;
    final_month := GREATEST(
        month_end,
        date_trunc('month', CURRENT_TIMESTAMP)::timestamp + INTERVAL '12 months'
    );

    WHILE month_start <= final_month LOOP
        partition_name := 'audit_logs_' || to_char(month_start, 'YYYY_MM');
        EXECUTE format(
            'CREATE TABLE public.%I PARTITION OF public.audit_logs FOR VALUES FROM (%L) TO (%L)',
            partition_name,
            month_start,
            month_start + INTERVAL '1 month'
        );
        month_start := month_start + INTERVAL '1 month';
    END LOOP;
END $$;

CREATE TABLE public.audit_logs_default PARTITION OF public.audit_logs DEFAULT;

INSERT INTO public.audit_logs (id, action, entity_type, entity_id, actor, details, created_at)
SELECT id, action, entity_type, entity_id, actor, details, created_at
FROM public.audit_logs_pre_partition;

-- Advance the new identity sequence past copied IDs so subsequent inserts don't collide.
SELECT setval(
    pg_get_serial_sequence('public.audit_logs', 'id'),
    COALESCE((SELECT max(id) FROM public.audit_logs), 1),
    EXISTS (SELECT 1 FROM public.audit_logs)
);

-- Parent indexes are propagated to every current and future partition.
CREATE INDEX ix_audit_logs_partitioned_created_at
    ON public.audit_logs (created_at DESC);
CREATE INDEX ix_audit_logs_partitioned_entity
    ON public.audit_logs (entity_type, entity_id, created_at DESC);
CREATE INDEX ix_audit_logs_partitioned_actor
    ON public.audit_logs (actor, created_at DESC);

COMMIT;

