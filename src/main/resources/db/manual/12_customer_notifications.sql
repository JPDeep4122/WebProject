-- Add persistent customer notifications to an existing PostgreSQL / Neon database.
-- Safe to run repeatedly; existing data and tables are preserved.
BEGIN;

CREATE TABLE IF NOT EXISTS user_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    type VARCHAR(30) NOT NULL,
    title VARCHAR(160) NOT NULL,
    message VARCHAR(1000) NOT NULL,
    reference_type VARCHAR(30),
    reference_id BIGINT,
    reference_key VARCHAR(120),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    read_at TIMESTAMP
);

CREATE INDEX IF NOT EXISTS ix_user_notifications_user_created
    ON user_notifications(user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_user_notifications_user_unread
    ON user_notifications(user_id, created_at DESC) WHERE read_at IS NULL;

COMMIT;
