-- PostgreSQL migration for the current English-named JPA schema.
-- Run only after users, branches and products already exist.

BEGIN;

CREATE TABLE IF NOT EXISTS orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_code VARCHAR(50) NOT NULL UNIQUE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    branch_id BIGINT REFERENCES branches(id) ON DELETE SET NULL,
    total_amount NUMERIC(15, 2) NOT NULL,
    shipping_fee NUMERIC(15, 2) NOT NULL DEFAULT 0,
    discount_amount NUMERIC(15, 2) NOT NULL DEFAULT 0,
    final_amount NUMERIC(15, 2) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    recipient_name VARCHAR(100) NOT NULL,
    recipient_phone VARCHAR(20) NOT NULL,
    shipping_address TEXT NOT NULL,
    note TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_orders_amounts CHECK (
        total_amount >= 0 AND shipping_fee >= 0
        AND discount_amount >= 0 AND final_amount >= 0
    ),
    CONSTRAINT ck_orders_status CHECK (status IN (
        'PENDING', 'CONFIRMED', 'PROCESSING', 'SHIPPING', 'DELIVERED',
        'CANCELLED', 'RETURN_REQUESTED', 'RETURNED'
    ))
);

CREATE TABLE IF NOT EXISTS order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    quantity INTEGER NOT NULL,
    price NUMERIC(15, 2) NOT NULL,
    subtotal NUMERIC(15, 2) NOT NULL,
    CONSTRAINT ck_order_items_quantity CHECK (quantity > 0),
    CONSTRAINT ck_order_items_amounts CHECK (price >= 0 AND subtotal >= 0)
);

CREATE TABLE IF NOT EXISTS payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL UNIQUE REFERENCES orders(id) ON DELETE CASCADE,
    payment_method VARCHAR(30) NOT NULL,
    payment_status VARCHAR(30) NOT NULL DEFAULT 'PENDING',
    amount NUMERIC(15, 2) NOT NULL,
    transaction_no VARCHAR(100),
    payment_time TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_payments_amount CHECK (amount >= 0),
    CONSTRAINT ck_payments_method CHECK (payment_method IN (
        'COD', 'VNPAY', 'MOMO', 'BANK_TRANSFER'
    )),
    CONSTRAINT ck_payments_status CHECK (payment_status IN (
        'PENDING', 'SUCCESS', 'FAILED', 'REFUNDED'
    ))
);

CREATE TABLE IF NOT EXISTS delivery_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL UNIQUE REFERENCES orders(id) ON DELETE CASCADE,
    shipper_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    status VARCHAR(30) NOT NULL DEFAULT 'ASSIGNED',
    assigned_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    picked_up_at TIMESTAMP,
    completed_at TIMESTAMP,
    failure_reason TEXT,
    proof_image VARCHAR(255),
    CONSTRAINT ck_delivery_assignments_status CHECK (status IN (
        'ASSIGNED', 'PICKED_UP', 'DELIVERING', 'DELIVERED_SUCCESS',
        'DELIVERED_FAILED', 'REJECTED'
    ))
);

CREATE TABLE IF NOT EXISTS branch_inventory (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id BIGINT NOT NULL REFERENCES branches(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
    stock_quantity INTEGER NOT NULL DEFAULT 0,
    reserved_quantity INTEGER NOT NULL DEFAULT 0,
    available_quantity INTEGER NOT NULL DEFAULT 0,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_branch_inventory_branch_product UNIQUE (branch_id, product_id),
    CONSTRAINT ck_branch_inventory_stock CHECK (stock_quantity >= 0),
    CONSTRAINT ck_branch_inventory_reserved CHECK (
        reserved_quantity >= 0 AND reserved_quantity <= stock_quantity
    ),
    CONSTRAINT ck_branch_inventory_available CHECK (
        available_quantity = stock_quantity - reserved_quantity
    )
);

CREATE INDEX IF NOT EXISTS ix_orders_user_created
    ON orders(user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_orders_branch_status_created
    ON orders(branch_id, status, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_order_items_order
    ON order_items(order_id);
CREATE INDEX IF NOT EXISTS ix_order_items_product
    ON order_items(product_id);
CREATE UNIQUE INDEX IF NOT EXISTS uq_payments_transaction_no
    ON payments(transaction_no) WHERE transaction_no IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_delivery_shipper_status
    ON delivery_assignments(shipper_id, status);
CREATE INDEX IF NOT EXISTS ix_branch_inventory_product
    ON branch_inventory(product_id);

COMMIT;
