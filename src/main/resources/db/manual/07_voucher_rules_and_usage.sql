BEGIN;

DO $$
BEGIN
    IF EXISTS (
        SELECT UPPER(BTRIM(code))
        FROM public.promotions
        GROUP BY UPPER(BTRIM(code))
        HAVING COUNT(*) > 1
    ) THEN
        RAISE EXCEPTION
            'Có mã voucher trùng sau khi chuẩn hóa. Kiểm tra promotions trước.';
    END IF;
END;
$$;

UPDATE public.promotions
SET code = UPPER(BTRIM(code));

CREATE UNIQUE INDEX IF NOT EXISTS ux_promotions_normalized_code
    ON public.promotions (UPPER(BTRIM(code)));

ALTER TABLE public.promotions
    ALTER COLUMN discount_percent DROP NOT NULL;

ALTER TABLE public.promotions
    ADD COLUMN IF NOT EXISTS discount_type VARCHAR(20)
        NOT NULL DEFAULT 'FIXED',
    ADD COLUMN IF NOT EXISTS discount_amount NUMERIC(15, 2),
    ADD COLUMN IF NOT EXISTS max_discount_amount NUMERIC(15, 2),
    ADD COLUMN IF NOT EXISTS min_order_amount NUMERIC(15, 2)
        NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS required_payment_method VARCHAR(30),
    ADD COLUMN IF NOT EXISTS new_customer_only BOOLEAN
        NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS per_user_limit INTEGER;

ALTER TABLE public.promotions
    ALTER COLUMN discount_type SET DEFAULT 'FIXED';


CREATE TABLE IF NOT EXISTS public.promotion_categories (
    promotion_id BIGINT NOT NULL
        REFERENCES public.promotions(id),
    category_id BIGINT NOT NULL
        REFERENCES public.categories(id),

    PRIMARY KEY (promotion_id, category_id)
);

-- Chụp lại mã đã áp dụng trên đơn.
ALTER TABLE public.orders
    ADD COLUMN IF NOT EXISTS voucher_code VARCHAR(50);

-- Lịch sử sử dụng voucher theo từng đơn.
CREATE TABLE IF NOT EXISTS public.voucher_usages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    order_id BIGINT NOT NULL UNIQUE
        REFERENCES public.orders(id),

    promotion_id BIGINT NOT NULL
        REFERENCES public.promotions(id),

    user_id BIGINT NOT NULL
        REFERENCES public.users(id),

    discount_amount NUMERIC(15, 2) NOT NULL
        CHECK (discount_amount >= 0),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    released_at TIMESTAMPTZ,
    release_reason VARCHAR(100)
);

CREATE INDEX IF NOT EXISTS ix_voucher_usages_customer
    ON public.voucher_usages(promotion_id, user_id)
    WHERE released_at IS NULL;

COMMIT;
