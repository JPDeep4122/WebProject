-- PostgreSQL / Neon target schema based on Untitled Diagram.drawio.
-- Vietnamese table names are transliterated to ASCII; column names are English.

CREATE TABLE khach_hang (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name       VARCHAR(150) NOT NULL,
    email           VARCHAR(254) NOT NULL UNIQUE,
    birth_date      DATE,
    gender          VARCHAR(30),
    phone_number    VARCHAR(30),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_khach_hang_gender
        CHECK (gender IS NULL OR gender IN ('female', 'male', 'non_binary', 'prefer_not_to_say'))
);

CREATE TABLE vai_tro (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name       VARCHAR(60) NOT NULL UNIQUE,
    description     TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE tai_khoan (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id     BIGINT UNIQUE REFERENCES khach_hang(id) ON DELETE SET NULL,
    phone_number    VARCHAR(30),
    password_hash   VARCHAR(255),
    status          VARCHAR(20) NOT NULL DEFAULT 'pending',
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_login_at   TIMESTAMPTZ,
    CONSTRAINT ck_tai_khoan_status
        CHECK (status IN ('pending', 'active', 'locked', 'disabled'))
);

CREATE TABLE tai_khoan_vai_tro (
    account_id      BIGINT NOT NULL REFERENCES tai_khoan(id) ON DELETE CASCADE,
    role_id         BIGINT NOT NULL REFERENCES vai_tro(id) ON DELETE RESTRICT,
    assigned_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (account_id, role_id)
);

CREATE TABLE nha_cung_cap_xac_thuc (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id          BIGINT NOT NULL REFERENCES tai_khoan(id) ON DELETE CASCADE,
    provider            VARCHAR(50) NOT NULL,
    provider_email      VARCHAR(254),
    provider_user_id    VARCHAR(255) NOT NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_login_at       TIMESTAMPTZ,
    CONSTRAINT uq_auth_provider_user UNIQUE (provider, provider_user_id),
    CONSTRAINT uq_auth_provider_account UNIQUE (account_id, provider)
);

CREATE TABLE chi_nhanh (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(150) NOT NULL,
    address         VARCHAR(500) NOT NULL,
    phone_number    VARCHAR(30),
    status          VARCHAR(20) NOT NULL DEFAULT 'active',
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_chi_nhanh_status CHECK (status IN ('active', 'inactive'))
);

CREATE TABLE nhan_vien_chi_nhanh (
    account_id      BIGINT PRIMARY KEY REFERENCES tai_khoan(id) ON DELETE CASCADE,
    branch_id       BIGINT NOT NULL REFERENCES chi_nhanh(id) ON DELETE RESTRICT,
    assigned_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    status          VARCHAR(20) NOT NULL DEFAULT 'active',
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_login_at   TIMESTAMPTZ,
    CONSTRAINT ck_nhan_vien_status CHECK (status IN ('active', 'inactive', 'suspended'))
);

CREATE TABLE danh_muc (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(120) NOT NULL UNIQUE,
    parent_category_id  BIGINT REFERENCES danh_muc(id) ON DELETE RESTRICT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_danh_muc_not_own_parent CHECK (parent_category_id IS NULL OR parent_category_id <> id)
);

CREATE TABLE thuong_hieu (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(120) NOT NULL UNIQUE,
    logo_url        VARCHAR(1000),
    status          VARCHAR(20) NOT NULL DEFAULT 'active',
    CONSTRAINT ck_thuong_hieu_status CHECK (status IN ('active', 'inactive'))
);

CREATE TABLE san_pham (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(255) NOT NULL,
    description     TEXT,
    brand_id        BIGINT REFERENCES thuong_hieu(id) ON DELETE SET NULL,
    category_id     BIGINT REFERENCES danh_muc(id) ON DELETE SET NULL,
    status          VARCHAR(20) NOT NULL DEFAULT 'draft',
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_san_pham_status CHECK (status IN ('draft', 'active', 'inactive', 'archived'))
);

CREATE TABLE bien_the_san_pham (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id      BIGINT NOT NULL REFERENCES san_pham(id) ON DELETE CASCADE,
    sku             VARCHAR(80) NOT NULL UNIQUE,
    price           NUMERIC(18, 2) NOT NULL,
    status          VARCHAR(20) NOT NULL DEFAULT 'active',
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_variant_price CHECK (price >= 0),
    CONSTRAINT ck_variant_status CHECK (status IN ('active', 'inactive')),
    CONSTRAINT uq_variant_product_id UNIQUE (product_id, id)
);

CREATE TABLE anh_san_pham (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id          BIGINT NOT NULL REFERENCES san_pham(id) ON DELETE CASCADE,
    image_view          VARCHAR(80),
    image_url           VARCHAR(1000) NOT NULL,
    cloudinary_public_id VARCHAR(255),
    alt_text            VARCHAR(255),
    is_primary          BOOLEAN NOT NULL DEFAULT FALSE,
    sort_order          INTEGER NOT NULL DEFAULT 0,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_product_image_sort CHECK (sort_order >= 0)
);

CREATE TABLE thuoc_tinh (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(120) NOT NULL UNIQUE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE gia_tri_thuoc_tinh (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attribute_id    BIGINT NOT NULL REFERENCES thuoc_tinh(id) ON DELETE CASCADE,
    value           VARCHAR(160) NOT NULL,
    CONSTRAINT uq_attribute_value UNIQUE (attribute_id, value),
    CONSTRAINT uq_attribute_value_id UNIQUE (attribute_id, id)
);

CREATE TABLE bien_the_thuoc_tinh (
    variant_id          BIGINT NOT NULL REFERENCES bien_the_san_pham(id) ON DELETE CASCADE,
    attribute_value_id  BIGINT NOT NULL REFERENCES gia_tri_thuoc_tinh(id) ON DELETE CASCADE,
    PRIMARY KEY (variant_id, attribute_value_id)
);

CREATE TABLE ton_kho_chi_nhanh (
    branch_id           BIGINT NOT NULL REFERENCES chi_nhanh(id) ON DELETE CASCADE,
    variant_id          BIGINT NOT NULL REFERENCES bien_the_san_pham(id) ON DELETE CASCADE,
    quantity            INTEGER NOT NULL DEFAULT 0,
    reserved_quantity   INTEGER NOT NULL DEFAULT 0,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (branch_id, variant_id),
    CONSTRAINT ck_inventory_quantity CHECK (quantity >= 0),
    CONSTRAINT ck_inventory_reserved CHECK (reserved_quantity >= 0 AND reserved_quantity <= quantity)
);

CREATE TABLE khuyen_mai (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(180) NOT NULL,
    starts_at       TIMESTAMPTZ NOT NULL,
    ends_at         TIMESTAMPTZ NOT NULL,
    status          VARCHAR(20) NOT NULL DEFAULT 'scheduled',
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_promotion_dates CHECK (ends_at > starts_at),
    CONSTRAINT ck_promotion_status CHECK (status IN ('scheduled', 'active', 'paused', 'ended'))
);

CREATE TABLE san_pham_khuyen_mai (
    promotion_id    BIGINT NOT NULL REFERENCES khuyen_mai(id) ON DELETE CASCADE,
    product_id      BIGINT NOT NULL REFERENCES san_pham(id) ON DELETE CASCADE,
    discount_type   VARCHAR(20) NOT NULL DEFAULT 'percentage',
    discount_value  NUMERIC(12, 2) NOT NULL,
    PRIMARY KEY (promotion_id, product_id),
    CONSTRAINT ck_promotion_discount_type CHECK (discount_type IN ('percentage', 'fixed_amount')),
    CONSTRAINT ck_promotion_discount_value CHECK (
        discount_value > 0 AND (discount_type <> 'percentage' OR discount_value <= 100)
    )
);

CREATE TABLE gio_hang (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id      BIGINT REFERENCES tai_khoan(id) ON DELETE CASCADE,
    session_id      VARCHAR(120),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_cart_owner CHECK (account_id IS NOT NULL OR session_id IS NOT NULL)
);

CREATE TABLE chi_tiet_gio_hang (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id         BIGINT NOT NULL REFERENCES gio_hang(id) ON DELETE CASCADE,
    variant_id      BIGINT NOT NULL REFERENCES bien_the_san_pham(id) ON DELETE RESTRICT,
    quantity        INTEGER NOT NULL DEFAULT 1,
    is_selected     BOOLEAN NOT NULL DEFAULT TRUE,
    added_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_cart_variant UNIQUE (cart_id, variant_id),
    CONSTRAINT ck_cart_item_quantity CHECK (quantity > 0)
);

CREATE TABLE dia_chi_giao_hang (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id          BIGINT NOT NULL REFERENCES tai_khoan(id) ON DELETE CASCADE,
    recipient_name      VARCHAR(150) NOT NULL,
    phone_number        VARCHAR(30) NOT NULL,
    province            VARCHAR(120),
    district            VARCHAR(120),
    ward                VARCHAR(120),
    street_address      VARCHAR(500) NOT NULL,
    is_default          BOOLEAN NOT NULL DEFAULT FALSE,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE hoa_don (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_code          VARCHAR(50) NOT NULL UNIQUE,
    account_id          BIGINT NOT NULL REFERENCES tai_khoan(id) ON DELETE RESTRICT,
    branch_id           BIGINT REFERENCES chi_nhanh(id) ON DELETE SET NULL,
    total_amount        NUMERIC(18, 2) NOT NULL DEFAULT 0,
    shipping_fee        NUMERIC(18, 2) NOT NULL DEFAULT 0,
    discount_amount     NUMERIC(18, 2) NOT NULL DEFAULT 0,
    final_amount        NUMERIC(18, 2) NOT NULL DEFAULT 0,
    status              VARCHAR(30) NOT NULL DEFAULT 'pending',
    recipient_name      VARCHAR(150) NOT NULL,
    recipient_phone     VARCHAR(30) NOT NULL,
    shipping_address    TEXT NOT NULL,
    note                TEXT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_order_amounts CHECK (
        total_amount >= 0 AND shipping_fee >= 0 AND discount_amount >= 0 AND final_amount >= 0
    ),
    CONSTRAINT ck_order_status CHECK (
        status IN ('pending', 'confirmed', 'processing', 'shipping', 'completed', 'cancelled', 'refunded')
    )
);

CREATE TABLE chi_tiet_hoa_don (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id            BIGINT NOT NULL REFERENCES hoa_don(id) ON DELETE CASCADE,
    variant_id          BIGINT NOT NULL REFERENCES bien_the_san_pham(id) ON DELETE RESTRICT,
    product_name_snapshot VARCHAR(255) NOT NULL,
    sku_snapshot        VARCHAR(80) NOT NULL,
    quantity            INTEGER NOT NULL,
    unit_price          NUMERIC(18, 2) NOT NULL,
    discount_amount     NUMERIC(18, 2) NOT NULL DEFAULT 0,
    line_total          NUMERIC(18, 2) NOT NULL,
    CONSTRAINT uq_order_variant UNIQUE (order_id, variant_id),
    CONSTRAINT ck_order_item_quantity CHECK (quantity > 0),
    CONSTRAINT ck_order_item_amounts CHECK (unit_price >= 0 AND discount_amount >= 0 AND line_total >= 0)
);

CREATE TABLE khuyen_mai_da_su_dung (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id          BIGINT NOT NULL REFERENCES tai_khoan(id) ON DELETE RESTRICT,
    promotion_id        BIGINT NOT NULL REFERENCES khuyen_mai(id) ON DELETE RESTRICT,
    order_id            BIGINT NOT NULL REFERENCES hoa_don(id) ON DELETE CASCADE,
    discount_amount     NUMERIC(18, 2) NOT NULL,
    used_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_account_promotion_use UNIQUE (account_id, promotion_id),
    CONSTRAINT uq_order_promotion_use UNIQUE (order_id, promotion_id),
    CONSTRAINT ck_used_discount CHECK (discount_amount >= 0)
);

CREATE TABLE thanh_toan (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id            BIGINT NOT NULL REFERENCES hoa_don(id) ON DELETE RESTRICT,
    payment_method      VARCHAR(30) NOT NULL,
    payment_status      VARCHAR(30) NOT NULL DEFAULT 'pending',
    amount              NUMERIC(18, 2) NOT NULL,
    transaction_number  VARCHAR(120),
    paid_at             TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_payment_amount CHECK (amount >= 0),
    CONSTRAINT ck_payment_status CHECK (payment_status IN ('pending', 'succeeded', 'failed', 'refunded'))
);

CREATE TABLE van_chuyen (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id            BIGINT NOT NULL UNIQUE REFERENCES hoa_don(id) ON DELETE CASCADE,
    shipper_account_id  BIGINT REFERENCES tai_khoan(id) ON DELETE SET NULL,
    status              VARCHAR(30) NOT NULL DEFAULT 'assigned',
    assigned_at         TIMESTAMPTZ,
    delivered_at        TIMESTAMPTZ,
    failure_reason      TEXT,
    proof_image_url     VARCHAR(1000),
    CONSTRAINT ck_shipping_status CHECK (
        status IN ('assigned', 'picked_up', 'delivering', 'delivered', 'failed', 'returned')
    )
);

CREATE TABLE danh_gia (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id              BIGINT NOT NULL REFERENCES tai_khoan(id) ON DELETE RESTRICT,
    product_id              BIGINT NOT NULL REFERENCES san_pham(id) ON DELETE RESTRICT,
    order_id                BIGINT REFERENCES hoa_don(id) ON DELETE SET NULL,
    comment                 TEXT,
    rating                  SMALLINT NOT NULL,
    status                  VARCHAR(20) NOT NULL DEFAULT 'pending',
    is_verified_purchase    BOOLEAN NOT NULL DEFAULT FALSE,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_review_rating CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT ck_review_status CHECK (status IN ('pending', 'published', 'hidden', 'rejected'))
);

CREATE TABLE nhat_ky_kiem_toan (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id      BIGINT REFERENCES tai_khoan(id) ON DELETE SET NULL,
    action          VARCHAR(100) NOT NULL,
    entity_id       BIGINT,
    entity_type     VARCHAR(100),
    details         JSONB,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
